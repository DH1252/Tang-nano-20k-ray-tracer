#!/usr/bin/env python3
"""Configure the core clock: PLL dividers and every frequency-dependent constant.

usage: python3 scripts/clock_config.py [MHz]      (default: $CORE_MHZ, else 75)

The core PLL (pll_core in rtl/gowin/clocks.v) runs from the video PLL's
CLKOUTD3, 126 / 3 = 42 MHz, so the core clock is 42 * FBDIV / IDIV MHz with
ODIV setting the VCO. The closest setting within the GW2A rPLL limits is
chosen (PFD >= 3 MHz, VCO 500..1250 MHz), never above the target, so the
timing a build was checked at is not exceeded. The UART divider and the SDRAM
refresh interval follow from the frequency actually produced.

Writes, from the templates in rtl/, sim/ and constraints/:
  build/clocks.v            Gowin clocks module (the project builds this one)
  build/tangnano20k.sdc     timing constraints with the core clock's ratio
  build/clocks_sim.v        clock stand-in for the system simulation
  build/clock.vh            constants for the testbenches
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
REF_MHZ = 42.0           # pll_ser CLKOUTD3: 126 / 3
ODIVS = (2, 4, 8, 16, 32, 48, 64, 80, 96, 112, 128)
MIN_MHZ, MAX_MHZ = 25.0, 100.0   # SDRAM timings are sized for 100 MHz at most
BAUD = 115200


def solve(target):
    best = None
    for idiv in range(1, 65):
        pfd = REF_MHZ / idiv
        if pfd < 3.0:
            break
        for fbdiv in range(1, 65):
            f = REF_MHZ * fbdiv / idiv
            if f > target + 1e-9:
                break
            for odiv in ODIVS:
                if 500.0 <= f * odiv <= 1250.0:
                    key = (abs(f - target), -pfd)
                    if best is None or key < best[0]:
                        best = (key, idiv, fbdiv, odiv, f)
                    break
    _, idiv, fbdiv, odiv, f = best
    return idiv, fbdiv, odiv, f


def sub(text, name, value, path):
    new, n = re.subn(r"(localparam\s+(?:\[[^\]]*\]\s*)?%s\s*=\s*)[^;]*;" % name, r"\g<1>%s;" % value, text)
    if n != 1:
        sys.exit(f"clock_config: {name} not found in {path}")
    return new


def render(src, dst, values):
    path = os.path.join(ROOT, src)
    text = open(path).read()
    for name, value in values.items():
        text = sub(text, name, value, src)
    header = f"// Generated by scripts/clock_config.py from {src}; edit the template, not this file.\n"
    with open(os.path.join(ROOT, dst), "w") as f:
        f.write(header + text)


def main():
    target = float(sys.argv[1] if len(sys.argv) > 1 else os.environ.get("CORE_MHZ", "75"))
    if not MIN_MHZ <= target <= MAX_MHZ:
        sys.exit(f"clock_config: core clock must be {MIN_MHZ:g}..{MAX_MHZ:g} MHz, got {target:g}")
    idiv, fbdiv, odiv, f = solve(target)
    uart_div = round(f * 1e6 / BAUD)
    ref_interval = min(1023, int(f * 8))      # refresh every 8 us (spec: 15.6 us)
    centi_mhz = round(f * 100)
    half_ps = round(1e6 / f / 2)
    os.makedirs(os.path.join(ROOT, "build"), exist_ok=True)

    consts = {"CORE_IDIV_SEL": idiv - 1, "CORE_FBDIV_SEL": fbdiv - 1, "CORE_ODIV_SEL": odiv,
              "UART_DIV": uart_div, "REF_INTERVAL": ref_interval, "CORE_CMHZ": centi_mhz}
    render("rtl/gowin/clocks.v", "build/clocks.v", consts)
    render("sim/clocks_sim.v", "build/clocks_sim.v",
           {"CORE_HALF_PS": half_ps, "UART_DIV": uart_div, "REF_INTERVAL": ref_interval, "CORE_CMHZ": centi_mhz})

    sdc = open(os.path.join(ROOT, "constraints/tangnano20k.sdc")).read()
    # clk_core = clk_ser / 3 * FBDIV / IDIV
    sdc, n = re.subn(r"(-name clk_core .*?-multiply_by )\d+( -divide_by )\d+", r"\g<1>%d\g<2>%d" % (fbdiv, 3 * idiv), sdc)
    if n != 1:
        sys.exit("clock_config: clk_core clock not found in constraints/tangnano20k.sdc")
    sdc = re.sub(r"(//   clk_core = ).*", r"\g<1>clk_ser * %d / %d  %.3f MHz (CLKOUTD3 = /3, then pll_core * %d / %d)"
                 % (fbdiv, 3 * idiv, f, fbdiv, idiv), sdc)
    with open(os.path.join(ROOT, "build/tangnano20k.sdc"), "w") as out:
        out.write("// Generated by scripts/clock_config.py from constraints/tangnano20k.sdc.\n" + sdc)

    with open(os.path.join(ROOT, "build/clock.vh"), "w") as out:
        out.write(f"// Generated by scripts/clock_config.py: core clock {f:.4f} MHz\n"
                  f"localparam real CORE_MHZ = {f:.6f};\n"
                  f"localparam integer CORE_PERIOD_PS = {2 * half_ps};\n"
                  f"localparam integer UART_DIV = {uart_div};\n")

    note = "" if abs(f - target) < 1e-9 else f" (closest to {target:g})"
    print(f"core clock {f:.4f} MHz{note}: pll_core 42 * {fbdiv} / {idiv}, VCO {f * odiv:.0f} MHz, "
          f"PFD {REF_MHZ / idiv:.2f} MHz; UART /{uart_div}, refresh every {ref_interval} cycles")


if __name__ == "__main__":
    main()
